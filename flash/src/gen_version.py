#!/usr/bin/env python3
"""Generate compact Flash-Tool version pixels from the repository VERSION."""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
LOWER = {
    'p': [0, 0, 30, 17, 30, 16, 16],
    'l': [12, 4, 4, 4, 4, 4, 14],
    'u': [0, 0, 17, 17, 17, 19, 13],
    's': [0, 0, 15, 16, 14, 1, 30],
}


def rows(label, font):
    width = len(label) * 6 - 1
    if width > 124:
        raise ValueError('Flash-Tool version label exceeds display width')
    out = [[0] * 16 for _ in range(7)]
    left = (128 - width) // 2
    for i, c in enumerate(label):
        glyph = LOWER.get(c, font[ord(c.upper()) - 32])
        for y, bits in enumerate(glyph):
            for x in range(5):
                if bits & (16 >> x):
                    px = left + i * 6 + x
                    out[y][px // 8] |= 1 << (7 - px % 8)
    return out


def main():
    version = (ROOT / 'VERSION').read_text().strip()
    if not re.fullmatch(r'[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?', version):
        raise ValueError('Unsupported VERSION format')
    values = [int(v, 16) for v in re.findall(r'0x[0-9a-fA-F]+', (ROOT / 'feld/src/feld/font.h').read_text())]
    assert len(values) == 96 * 7
    font = [values[i:i + 7] for i in range(0, len(values), 7)]
    pixels = rows('PARAMIX', font) + rows(version, font)
    out = '/* Generated by gen_version.py from VERSION; rebuild with flash/src/build.sh. */\n'
    out += '#ifndef FLASH_VERSION_H\n#define FLASH_VERSION_H\n'
    out += f'static const char flash_version_tag[] __attribute__((used)) = "PMXVER:{version}";\n'
    out += 'static const unsigned char flash_version_bits[14][16]={\n'
    out += ',\n'.join('  {' + ','.join(f'0x{b:02x}' for b in row) + '}' for row in pixels)
    out += '\n};\n#endif\n'
    (HERE / 'version.h').write_text(out)


if __name__ == '__main__':
    main()
