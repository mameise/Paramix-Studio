#!/usr/bin/env python3
"""Generate compact Flash Tool labels from the Paramix Menu font."""

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
FONT = HERE.parents[1] / "feld/src/feld/font.h"
ASSETS = HERE / "assets.h"
HINTS = HERE / "reset_hint.h"
WIDTH = 128
TITLE = ("title_paramix", "PARAMIX", 1)
SUBTITLE = ("title_flash_tool", "FLASH TOOL", 2)
STATUSES = (
    ("st_ready", "READY", 2),
    ("st_reading", "READING", 2),
    ("st_writing", "WRITING", 2),
    ("st_done", "DONE", 2),
)
RESET_HINTS = ("RESET LOCKED", "HOLD C TO RESET", "RELEASE C")


def load_font():
    values = [int(value, 16) for value in re.findall(r"0x[0-9a-fA-F]+", FONT.read_text())]
    assert len(values) == 96 * 7, "Unexpected font dimensions"
    return [values[index:index + 7] for index in range(0, len(values), 7)]


def render_mask(label, scale, font):
    text_width = (len(label) * 6 - 1) * scale
    assert text_width <= WIDTH
    left = (WIDTH - text_width) // 2
    packed = bytearray(WIDTH * 7 * scale // 8)
    for i, char in enumerate(label):
        for y, row in enumerate(font[ord(char) - 32]):
            for x in range(5):
                if row & (16 >> x):
                    for dy in range(scale):
                        for dx in range(scale):
                            pos = (y * scale + dy) * WIDTH + left + (i * 6 + x) * scale + dx
                            packed[pos // 8] |= 0x80 >> (pos % 8)
    return packed


def hex_bytes(data):
    return ",".join(f"0x{byte:02x}" for byte in data)


def main():
    font = load_font()
    source = "/* Generated by gen_status.py from the Paramix Menu font. */\n"
    source += "#ifndef ASSETS_H\n#define ASSETS_H\n"
    for name, label, scale in (TITLE, SUBTITLE, *STATUSES):
        mask = render_mask(label, scale, font)
        source += f"static const unsigned char {name}[{len(mask)}]={{" + hex_bytes(mask) + "};\n"
    ASSETS.write_text(source + "#endif\n")
    hints = "/* Generated by gen_status.py: 128x7 MSB-first reset hints. */\n"
    hints += "#ifndef RESET_HINT_H\n#define RESET_HINT_H\n"
    hints += "static const unsigned char reset_hint_bits[3][112]={\n"
    hints += ",\n".join("  {" + hex_bytes(render_mask(label, 1, font)) + "}" for label in RESET_HINTS)
    HINTS.write_text(hints + "\n};\n#endif\n")


if __name__ == "__main__":
    main()
