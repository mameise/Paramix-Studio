#!/usr/bin/env python3
"""Regenerate compact Flash-Tool status/hint pixels from the project's font.

Run from any directory. Statuses store a little-endian RGB565 foreground then
a 128x16 MSB-first one-bit mask; the background artwork stays untouched.
"""

import re
from pathlib import Path


HERE = Path(__file__).resolve().parent
FONT = HERE.parents[1] / "feld/src/feld/font.h"
ASSETS = HERE / "assets.h"
HINTS = HERE / "reset_hint.h"
WIDTH, HEIGHT = 128, 16
BACKGROUND = 0x0883
STATUSES = (
    ("st_bereit", "st_ready", "READY", 0x7EF1),
    ("st_lesen", "st_reading", "READING", 0xEF7E),
    ("st_schreiben", "st_writing", "WRITING", 0xF5AB),
    ("st_fertig", "st_done", "DONE", 0x7EF1),
)
RESET_HINTS = ("RESET LOCKED", "HOLD C TO RESET", "RELEASE C")


def load_font():
    values = [int(value, 16) for value in re.findall(r"0x[0-9a-fA-F]+", FONT.read_text())]
    assert len(values) == 96 * 7, "Unexpected font dimensions"
    return [values[index:index + 7] for index in range(0, len(values), 7)]


def pack_mask(pixels, color):
    assert len(pixels) % 8 == 0
    packed = bytearray(len(pixels) // 8)
    for i, pixel in enumerate(pixels):
        assert pixel in (BACKGROUND, color)
        if pixel == color:
            packed[i // 8] |= 0x80 >> (i % 8)
    return bytes(packed)


def render_hint(label, font):
    assert len(label) * 6 - 1 <= WIDTH
    pixels = [BACKGROUND] * (WIDTH * 7)
    left = (WIDTH - (len(label) * 6 - 1)) // 2
    for i, char in enumerate(label):
        for y, row in enumerate(font[ord(char) - 32]):
            for x in range(5):
                if row & (16 >> x):
                    pixels[y * WIDTH + left + i * 6 + x] = 0xFFFF
    return pack_mask(pixels, 0xFFFF)


def render(text, color, font):
    pixels = [BACKGROUND] * (WIDTH * HEIGHT)
    # Match the original status baseline and nine-pixel letter height.
    left = (WIDTH - (len(text) * 8 - 1)) // 2
    for index, char in enumerate(text):
        glyph = font[ord(char) - 32]
        for y in range(9):
            row = glyph[y * 7 // 9]
            for x in range(7):
                if row & (16 >> (x * 5 // 7)):
                    pixels[(y + 5) * WIDTH + left + index * 8 + x] = color
    return pixels


def main():
    font = load_font()
    source = ASSETS.read_text()
    for old_name, name, label, color in STATUSES:
        pixels = render(label, color, font)
        packed = bytes((color & 255, color >> 8)) + pack_mask(pixels, color)
        declaration = "static const unsigned char " + name + "[258]={" + ",".join(f"0x{byte:02x}" for byte in packed) + "};"
        pattern = rf"static const unsigned (?:short|char) (?:{old_name}|{name})\[(?:2048|258)\]=\{{[^}}]*\}};"
        source, count = re.subn(pattern, lambda match: declaration, source)
        assert count == 1, f"Expected exactly one {name} bitmap"
    ASSETS.write_text(source)
    hints = "/* Generated by gen_status.py: 128x7 MSB-first reset hints. */\n"
    hints += "#ifndef RESET_HINT_H\n#define RESET_HINT_H\n"
    hints += "static const unsigned char reset_hint_bits[3][112]={\n"
    hints += ",\n".join("  {" + ",".join(f"0x{byte:02x}" for byte in render_hint(label, font)) + "}" for label in RESET_HINTS)
    hints += "\n};\n#endif\n"
    HINTS.write_text(hints)


if __name__ == "__main__":
    main()
