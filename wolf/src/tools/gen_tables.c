/* Paramix Wolf3D: the trig tables of BuildTables and CalcProjection (Wolf4SDL wl_main.c) for a 128 dot wide view,
 * written as C, so the Paradise program needs no floating point. gcc gen_tables.c -lm && ./a.out > ../pmx/pmx_tables.h */
#include <stdio.h>
#include <math.h>
#include <stdint.h>
#define PI 3.141592657
#define FINEANGLES 3600
#define ANGLES 360
#define ANGLEQUAD (ANGLES/4)
#define GLOBAL1 (1l<<16)
#define TILEGLOBAL GLOBAL1
#define MINDIST 0x5800l
#define FOCALLENGTH 0x5700l
#define VIEWGLOBAL 0x10000
#define VIEWWIDTH 128
int main (void)
{
    static int32_t finetangent[FINEANGLES/4], sintable[ANGLES+ANGLES/4];
    static short pixelangle[VIEWWIDTH];
    const float radtoint = (float)(FINEANGLES/2/PI);
    for (int i=0;i<FINEANGLES/8;i++) { double tang=tan((i+0.5)/radtoint); finetangent[i]=(int32_t)(tang*GLOBAL1); finetangent[FINEANGLES/4-1-i]=(int32_t)((1/tang)*GLOBAL1); }
    float angle=0, anglestep=(float)(PI/2/ANGLEQUAD);
    for (int i=0;i<ANGLEQUAD;i++) { int32_t value=(int32_t)(GLOBAL1*sin(angle)); sintable[i]=sintable[i+ANGLES]=sintable[ANGLES/2-i]=value; sintable[ANGLES-i]=sintable[ANGLES/2+i]=-value; angle+=anglestep; }
    sintable[ANGLEQUAD] = 65536; sintable[3*ANGLEQUAD] = -65536;
    double facedist = FOCALLENGTH+MINDIST; int halfview = VIEWWIDTH/2;
    int32_t scale = (int32_t)(halfview*facedist/(VIEWGLOBAL/2));
    int32_t heightnumerator = (TILEGLOBAL*scale)>>6;
    for (int i=0;i<halfview;i++) { double tang=(int32_t)i*VIEWGLOBAL/VIEWWIDTH/facedist; float a=(float)atan(tang); int intang=(int)(a*radtoint); pixelangle[halfview-1-i]=intang; pixelangle[halfview+i]=-intang; }
    printf ("/* generated by tools/gen_tables.c (BuildTables, CalcProjection of Wolf4SDL for a view 128 wide) */\n");
    printf ("#define PMX_T_SCALE %ld\n#define PMX_T_HEIGHTNUMERATOR %ld\n", (long)scale, (long)heightnumerator);
    printf ("const int32_t finetangent[%d] = {", FINEANGLES/4); for (int i=0;i<FINEANGLES/4;i++) printf ("%s%ld,", i%10?"":"\n", (long)finetangent[i]); printf ("\n};\n");
    printf ("const int32_t sintable[%d] = {", ANGLES+ANGLES/4); for (int i=0;i<ANGLES+ANGLES/4;i++) printf ("%s%ld,", i%10?"":"\n", (long)sintable[i]); printf ("\n};\n");
    printf ("static const short pmx_pixelangle[%d] = {", VIEWWIDTH); for (int i=0;i<VIEWWIDTH;i++) printf ("%s%d,", i%16?"":"\n", pixelangle[i]); printf ("\n};\n");
    return 0;
}
