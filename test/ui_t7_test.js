// T7Emu in the browser: V7 ROM and figures into a Paradise ROM, save, load again, remove a figure.
// node test/ui_t7_test.js <paradise.bin> <v7_rom.bin> <out_dir> <figure.bin...>
const { chromium } = require('playwright');
const fs = require('fs'), path = require('path');
const E = require('../src/emu.js');
(async () => {
  const [rom, v7, out, ...figs] = process.argv.slice(2);
  fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, acceptDownloads: true });
  const errors = []; page.on('pageerror', (e) => errors.push(e.message));
  await page.addInitScript(() => { try { localStorage.setItem('paramix-lang', 'de'); } catch (e) {} });
  await page.goto('file://' + path.resolve(__dirname, '../dist/ParamixStudio.html'));
  await page.setInputFiles('#fileRom', rom);
  await page.waitForSelector('#work.on', { timeout: 60000 });
  await page.click('.tab[data-tab="emu"]');
  await page.setInputFiles('#fileEmu', v7);
  await page.waitForTimeout(500);
  await page.setInputFiles('#fileT7Fig', figs);
  await page.waitForTimeout(500);
  console.log('Status:', (await page.textContent('#emuStat')).replace(/\n/g, ' | '));
  if (!(await page.$('.pdet'))) await page.click('#appsList .prow .ptog');   // 1.6.8: figures in the program's row
  console.log('Figuren:', await page.textContent('.pdet .chips'));
  console.log('Plan:', (await page.textContent('#plan')).slice(0, 160));
  await page.screenshot({ path: out + '/t7_1.png' });
  const [dl] = await Promise.all([page.waitForEvent('download', { timeout: 120000 }), page.click('#btnSave')]);
  const r1 = out + '/' + dl.suggestedFilename(); await dl.saveAs(r1);
  const c1 = E.t7Cfg(new Uint8Array(fs.readFileSync(r1)));
  console.log('ROM', path.basename(r1), 'figures', c1.figs.map((f) => f.name).join(', '));
  await page.setInputFiles('#fileRom', r1); await page.waitForTimeout(1500);
  await page.click('.tab[data-tab="emu"]');
  console.log('Nach Laden:', (await page.textContent('#emuStat')).replace(/\n/g, ' | '));
  if (!(await page.$('.pdet'))) await page.click('#appsList .prow .ptog');
  console.log('Figuren:', await page.textContent('.pdet .chips'));
  await page.click('.pdet .chips button'); await page.waitForTimeout(300);
  const [dl2] = await Promise.all([page.waitForEvent('download', { timeout: 120000 }), page.click('#btnSave')]);
  const r2 = out + '/second.bin'; await dl2.saveAs(r2);
  const c2 = E.t7Cfg(new Uint8Array(fs.readFileSync(r2)));
  console.log('nach Entfernen:', c2.figs.map((f) => f.name).join(', '));
  await page.screenshot({ path: out + '/t7_2.png' });
  // save.bin: into the ROM through the Save tab, out again
  const SV = require('../src/saves.js');
  const sv = new Uint8Array(4098); sv[0] = 3; for (let i = 2; i < 4098; i++) sv[i] = (i * 13) & 255;
  fs.writeFileSync(out + '/save_in.bin', sv);
  await page.setInputFiles('#fileRom', r2); await page.waitForTimeout(1500);
  await page.click('.tab[data-tab="save"]');
  console.log('Knopf:', await page.textContent('#btnEmuIn'), '| Export aktiv:', !(await page.isDisabled('#btnEmuOut')));
  await page.setInputFiles('#fileEmuSav', out + '/save_in.bin'); await page.waitForTimeout(300);
  console.log('Status:', await page.textContent('#saveStat'));
  const [dl3] = await Promise.all([page.waitForEvent('download', { timeout: 120000 }), page.click('#btnSave')]);
  const r3 = out + '/third.bin'; await dl3.saveAs(r3);
  const got = SV.t7SaveOut(new Uint8Array(fs.readFileSync(r3)));
  console.log('save.bin im ROM gleich:', !!got && Buffer.compare(Buffer.from(got), Buffer.from(sv)) === 0);
  await page.setInputFiles('#fileRom', r3); await page.waitForTimeout(1500);
  await page.click('.tab[data-tab="save"]');
  const [dl4] = await Promise.all([page.waitForEvent('download', { timeout: 30000 }), page.click('#btnEmuOut')]);
  const r4 = out + '/' + dl4.suggestedFilename(); await dl4.saveAs(r4);
  console.log('Export', path.basename(r4), 'gleich:', Buffer.compare(fs.readFileSync(r4), Buffer.from(sv)) === 0);
  await page.screenshot({ path: out + '/t7_3.png' });
  console.log('Fehler:', errors);
  await browser.close();
})();
